package com.example.practicaexamen;

public class Comida {
    int id;
    String nombre;
    String precio;
    String descripcion;

    public Comida(int id, String nombre, String precio, String descripcion) {
        this.id = id;
        this.nombre = nombre;
        this.precio = precio;
        this.descripcion = descripcion;
    }
}